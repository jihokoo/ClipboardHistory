import Foundation
import AppKit

/// Decides whether a copied item looks sensitive and must NOT be stored.
///
/// Two layers:
///  1. Pasteboard markers — password managers flag sensitive copies with
///     well-known types (nspasteboard.org convention). Cheap and reliable.
///  2. Content heuristics — known secret formats plus a generic high-entropy check.
///
/// This is best-effort: a short or unusual secret with no marker will not be caught.
/// Returns a short reason code (never the content) so callers can log metadata safely.
enum SecretFilter {

    // MARK: - Layer 1: pasteboard markers

    private static let markerTypes: [(NSPasteboard.PasteboardType, String)] = [
        (.init("org.nspasteboard.ConcealedType"), "concealed_marker"),
        (.init("org.nspasteboard.TransientType"), "transient_marker"),
        (.init("org.nspasteboard.AutoGeneratedType"), "autogenerated_marker"),
        (.init("com.agilebits.onepassword"), "1password_marker"),
    ]

    static func skipReason(pasteboard: NSPasteboard, text: String) -> String? {
        let types = Set(pasteboard.types ?? [])
        for (type, reason) in markerTypes where types.contains(type) {
            return reason
        }
        return skipReason(text: text)
    }

    // MARK: - Layer 2: content heuristics

    private static func rx(_ pattern: String) -> NSRegularExpression {
        // Patterns are literals below; a typo should fail loudly in development.
        try! NSRegularExpression(pattern: pattern)
    }

    private static let patterns: [(NSRegularExpression, String)] = [
        (rx(#"-----BEGIN [A-Z0-9 ]*PRIVATE KEY"#), "private_key"),
        (rx(#"\b(?:AKIA|ASIA)[0-9A-Z]{16}\b"#), "aws_access_key"),
        (rx(#"\bgh[pousr]_[A-Za-z0-9]{36,}\b"#), "github_token"),
        (rx(#"\bgithub_pat_[A-Za-z0-9_]{20,}"#), "github_token"),
        (rx(#"\bsk-[A-Za-z0-9_\-]{20,}"#), "api_key_sk"),
        (rx(#"\b[sr]k_(?:live|test)_[0-9a-zA-Z]{16,}"#), "stripe_key"),
        (rx(#"\bxox[abprs]-[A-Za-z0-9\-]{10,}"#), "slack_token"),
        (rx(#"\bAIza[0-9A-Za-z_\-]{35}\b"#), "google_api_key"),
        (rx(#"\bpub[0-9a-f]{32}\b"#), "datadog_client_token"),
        (rx(#"\beyJ[A-Za-z0-9_\-]{8,}\.eyJ[A-Za-z0-9_\-]{8,}\.[A-Za-z0-9_\-]{8,}"#), "jwt"),
        (rx(#"(?i)\bbearer\s+[A-Za-z0-9._~+/\-]{20,}"#), "bearer_token"),
        // .env / shell style assignment: NAME_WITH_SECRET=value
        (rx(#"(?im)^\s*(?:export\s+)?[A-Z0-9_]*(?:SECRET|TOKEN|PASSWORD|PASSWD|API_?KEY|PRIVATE_KEY|ACCESS_KEY)[A-Z0-9_]*\s*[=:]\s*\S{8,}"#), "env_secret_assignment"),
    ]

    static func skipReason(text: String) -> String? {
        let range = NSRange(text.startIndex..., in: text)
        for (regex, reason) in patterns where regex.firstMatch(in: text, range: range) != nil {
            return reason
        }

        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        if isSSN(trimmed) { return "ssn" }
        if isCardNumber(trimmed) { return "card_number" }
        if isHighEntropyToken(trimmed) { return "high_entropy_token" }
        return nil
    }

    private static func isSSN(_ s: String) -> Bool {
        s.range(of: #"^\d{3}-\d{2}-\d{4}$"#, options: .regularExpression) != nil
    }

    /// 13–19 digits (spaces/dashes allowed) that pass the Luhn checksum.
    private static func isCardNumber(_ s: String) -> Bool {
        guard s.range(of: #"^[\d \-]{13,23}$"#, options: .regularExpression) != nil else { return false }
        let digits = s.compactMap { $0.wholeNumberValue }
        guard (13...19).contains(digits.count) else { return false }
        var sum = 0
        for (i, d) in digits.reversed().enumerated() {
            if i % 2 == 1 {
                let doubled = d * 2
                sum += doubled > 9 ? doubled - 9 : doubled
            } else {
                sum += d
            }
        }
        return sum % 10 == 0
    }

    /// A single long, random-looking token (no whitespace). Thresholds are set so
    /// git SHAs and UUIDs (entropy <= ~4.0) and ordinary words/paths are not flagged.
    private static func isHighEntropyToken(_ s: String) -> Bool {
        guard (24...256).contains(s.count) else { return false }
        guard s.rangeOfCharacter(from: .whitespacesAndNewlines) == nil else { return false }
        guard !s.contains("://"), !s.hasPrefix("/"), !s.hasPrefix("~") else { return false }
        guard s.rangeOfCharacter(from: .letters) != nil,
              s.rangeOfCharacter(from: .decimalDigits) != nil else { return false }
        return shannonEntropy(s) >= 4.2
    }

    private static func shannonEntropy(_ s: String) -> Double {
        var counts: [Character: Int] = [:]
        for ch in s { counts[ch, default: 0] += 1 }
        let n = Double(s.count)
        return counts.values.reduce(0.0) { acc, c in
            let p = Double(c) / n
            return acc - p * log2(p)
        }
    }
}
